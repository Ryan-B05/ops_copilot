-- ============================================================
-- Ops Copilot: database schema
-- Six tables and one view for a waste collection business.
--
-- Tables are created in dependency order: a foreign key cannot
-- reference a table that does not exist yet.
--
-- All data is synthetic. PostgreSQL 18.
-- ============================================================


-- ------------------------------------------------------------
-- routes
--
-- vehicle_reg lives here although vehicles can be swapped
-- between routes. Known simplification for the prototype.
-- ------------------------------------------------------------
CREATE TABLE routes (
    route_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    area        TEXT NOT NULL,
    vehicle_reg TEXT NOT NULL,
    CONSTRAINT routes_name_unique UNIQUE (name)
);


-- ------------------------------------------------------------
-- drivers
--
-- Drivers are a separate table, not a column on routes. Several
-- drivers can cover one route and drivers leave. A driver name
-- stored on the route would rewrite history when it changed.
-- ------------------------------------------------------------
CREATE TABLE drivers (
    driver_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL,
    employee_ref TEXT NOT NULL,
    active       BOOLEAN NOT NULL,
    CONSTRAINT drivers_employee_ref_unique UNIQUE (employee_ref)
);


-- ------------------------------------------------------------
-- customers
--
-- Names are not unique, so the key is a plain integer.
-- route_id is the route the customer is on today.
-- ------------------------------------------------------------
CREATE TABLE customers (
    customer_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL,
    account_type TEXT NOT NULL
        CHECK (account_type IN ('household', 'commercial')),
    eircode      TEXT NOT NULL,
    route_id     INTEGER NOT NULL,
    status       TEXT NOT NULL
        CHECK (status IN ('active', 'inactive')),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (route_id) REFERENCES routes (route_id)
);


-- ------------------------------------------------------------
-- collections
--
-- route_id and driver_id are stored on each collection on
-- purpose. The customer row says where they are now; the
-- collection row says what happened on that day.
--
-- weight_kg is NULL for a missed collection. Zero would be a
-- real measurement and would drag down every average.
-- ------------------------------------------------------------
CREATE TABLE collections (
    collection_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INTEGER NOT NULL,
    route_id      INTEGER NOT NULL,
    driver_id     INTEGER NOT NULL,
    collected_at  TIMESTAMP NOT NULL,
    bin_type      TEXT NOT NULL
        CHECK (bin_type IN ('general', 'recycling', 'organic')),
    weight_kg     NUMERIC,
    status        TEXT NOT NULL
        CHECK (status IN ('collected', 'missed', 'contaminated')),
    FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    FOREIGN KEY (route_id)    REFERENCES routes (route_id),
    FOREIGN KEY (driver_id)   REFERENCES drivers (driver_id),
    CONSTRAINT weight_matches_status CHECK (
        (status = 'missed' AND weight_kg IS NULL)
     OR (status IN ('collected', 'contaminated') AND weight_kg IS NOT NULL)
    )
);

CREATE INDEX idx_collections_customer_date
    ON collections (customer_id, collected_at DESC);

CREATE INDEX idx_collections_date
    ON collections (collected_at);


-- ------------------------------------------------------------
-- invoices
--
-- Money is NUMERIC, not float. There is no status column:
-- paid, open and overdue are all derived from paid_at and
-- due_at, so a stored status would go stale at midnight.
-- Invoices are subscription billing and are not linked to
-- individual collections.
-- ------------------------------------------------------------
CREATE TABLE invoices (
    invoice_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    issued_at   DATE NOT NULL,
    due_at      DATE NOT NULL,
    amount_eur  NUMERIC(10, 2) NOT NULL,
    paid_at     DATE,
    FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT amount_positive CHECK (amount_eur >= 0)
);

CREATE VIEW invoice_status AS
SELECT invoice_id, customer_id, amount_eur, issued_at, due_at, paid_at,
       CASE WHEN paid_at IS NOT NULL    THEN 'paid'
            WHEN due_at  < CURRENT_DATE THEN 'overdue'
            ELSE 'open' END AS status
FROM invoices;


-- ------------------------------------------------------------
-- supplier_dockets
--
-- The only table meant to be filled by a machine (document
-- extraction, not built yet). A row is not trusted until a
-- person approves it, and the two approval columns must be
-- set together. source_file is kept for audit.
-- ------------------------------------------------------------
CREATE TABLE supplier_dockets (
    docket_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier     TEXT NOT NULL,
    docket_date  DATE NOT NULL,
    material     TEXT NOT NULL,
    tonnes       NUMERIC NOT NULL,
    charge_eur   NUMERIC(10, 2) NOT NULL,
    source_file  TEXT NOT NULL,
    extracted_at TIMESTAMP NOT NULL,
    approved_by  TEXT,
    approved_at  TIMESTAMP,
    CONSTRAINT tonnes_positive CHECK (tonnes > 0),
    CONSTRAINT approval_is_complete CHECK (
        (approved_by IS NULL     AND approved_at IS NULL)
     OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)
    )
);
